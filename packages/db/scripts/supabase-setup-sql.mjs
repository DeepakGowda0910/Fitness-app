#!/usr/bin/env node
/**
 * Writes supabase/setup.sql: every migration in order, plus Drizzle's
 * bookkeeping rows, as one script to paste into the Supabase SQL editor.
 * Running it there needs no database password on anyone's computer, and
 * later `drizzle-kit migrate` runs see these migrations as already applied.
 *
 *   node scripts/supabase-setup-sql.mjs
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const journal = JSON.parse(readFileSync(join(root, 'migrations/meta/_journal.json'), 'utf8'));

const parts = [
  '-- Fitness app: database setup for Supabase.',
  '-- Generated by packages/db/scripts/supabase-setup-sql.mjs. Do not edit by hand.',
  '-- Paste all of it into Supabase → SQL Editor → New query, then press Run.',
  '-- It runs as one transaction: either everything is created, or nothing is.',
  '',
  'BEGIN;',
  '',
  'CREATE SCHEMA IF NOT EXISTS drizzle;',
  'CREATE TABLE IF NOT EXISTS drizzle.__drizzle_migrations (id SERIAL PRIMARY KEY, hash text NOT NULL, created_at bigint);',
];

for (const entry of journal.entries) {
  const sql = readFileSync(join(root, 'migrations', `${entry.tag}.sql`), 'utf8');
  const hash = createHash('sha256').update(sql).digest('hex');
  parts.push(
    '',
    `-- ===== ${entry.tag} =====`,
    sql.replaceAll('--> statement-breakpoint', '').trim(),
    `INSERT INTO drizzle.__drizzle_migrations (hash, created_at) VALUES ('${hash}', ${entry.when});`,
  );
}

parts.push(
  '',
  '-- ===== Access for signed-in users =====',
  '-- Row-level security (above) decides which rows each user can see or change.',
  '-- Nothing in this app is meant for signed-out visitors, so they get no table access at all.',
  'GRANT USAGE ON SCHEMA public TO authenticated;',
  'GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO authenticated;',
  'REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon;',
  '',
  'COMMIT;',
  '',
);

const out = join(root, 'supabase/setup.sql');
writeFileSync(out, parts.join('\n'));
console.log(`Wrote ${out}`);
