#!/usr/bin/env node
/**
 * Writes supabase/setup.sql: every migration in order, plus Drizzle's
 * bookkeeping rows, as one script to paste into the Supabase SQL editor.
 * Running it there needs no database password on anyone's computer, and
 * later `drizzle-kit migrate` runs see these migrations as already applied.
 *
 * It also writes one update script per entry in UPDATES, for a project that
 * already ran an earlier setup.sql: just the newer migrations, the same way.
 *
 *   node scripts/supabase-setup-sql.mjs
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const journal = JSON.parse(readFileSync(join(root, 'migrations/meta/_journal.json'), 'utf8'));

/** Update scripts for existing projects: file name → the migrations it adds. */
const UPDATES = {
  'update-1-admin.sql': ['0005_admin_roles', '0006_admin_access'],
  'update-2-workouts.sql': ['0007_workouts', '0008_workouts_rls'],
};

function migrationSql(entry) {
  const sql = readFileSync(join(root, 'migrations', `${entry.tag}.sql`), 'utf8');
  const hash = createHash('sha256').update(sql).digest('hex');
  return [
    '',
    `-- ===== ${entry.tag} =====`,
    sql.replaceAll('--> statement-breakpoint', '').trim(),
    `INSERT INTO drizzle.__drizzle_migrations (hash, created_at) VALUES ('${hash}', ${entry.when});`,
  ];
}

const GRANTS = [
  '',
  '-- ===== Access for signed-in users =====',
  '-- Row-level security (above) decides which rows each user can see or change.',
  '-- Nothing in this app is meant for signed-out visitors, so they get no table access at all.',
  'GRANT USAGE ON SCHEMA public TO authenticated;',
  'GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO authenticated;',
  'REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon;',
];

const parts = [
  '-- Fitness app: database setup for Supabase.',
  '-- Generated by packages/db/scripts/supabase-setup-sql.mjs. Do not edit by hand.',
  '-- Paste all of it into Supabase → SQL Editor → New query, then press Run.',
  '-- It runs as one transaction: either everything is created, or nothing is.',
  '',
  'BEGIN;',
  '',
  'CREATE SCHEMA IF NOT EXISTS drizzle;',
  'CREATE TABLE IF NOT EXISTS drizzle.__drizzle_migrations (id SERIAL PRIMARY KEY, hash text NOT NULL, created_at bigint);',
  '-- Bookkeeping for schema changes. Only the database owner, who bypasses row-level security, uses it.',
  'ALTER TABLE drizzle.__drizzle_migrations ENABLE ROW LEVEL SECURITY;',
];

for (const entry of journal.entries) parts.push(...migrationSql(entry));
parts.push(...GRANTS, '', 'COMMIT;', '');

const out = join(root, 'supabase/setup.sql');
writeFileSync(out, parts.join('\n'));
console.log(`Wrote ${out}`);

for (const [file, tags] of Object.entries(UPDATES)) {
  const entries = tags.map((tag) => {
    const entry = journal.entries.find((e) => e.tag === tag);
    if (!entry) throw new Error(`Unknown migration ${tag}`);
    return entry;
  });
  const update = [
    `-- Fitness app: database update (${tags.join(', ')}).`,
    '-- Generated by packages/db/scripts/supabase-setup-sql.mjs. Do not edit by hand.',
    '-- For a project that already ran setup.sql before these were added.',
    '-- Paste all of it into Supabase → SQL Editor → New query, then press Run. Run it once.',
    '-- It runs as one transaction: either everything is applied, or nothing is.',
    '',
    'BEGIN;',
  ];
  for (const entry of entries) update.push(...migrationSql(entry));
  update.push(...GRANTS, '', 'COMMIT;', '');
  const path = join(root, 'supabase', file);
  writeFileSync(path, update.join('\n'));
  console.log(`Wrote ${path}`);
}
